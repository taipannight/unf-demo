DROP DATABASE IF EXISTS unf_demo;
CREATE DATABASE unf_demo ENCODING 'UTF8';
\connect unf_demo

CREATE TABLE organizations (
  id serial PRIMARY KEY, name text NOT NULL, inn varchar(12) NOT NULL, kpp varchar(9),
  ogrn varchar(15), address text, phone text);
CREATE TABLE nomenclature_groups (id serial PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE nomenclature (
  id serial PRIMARY KEY, code varchar(10) UNIQUE NOT NULL, name text NOT NULL,
  group_id int REFERENCES nomenclature_groups(id), unit varchar(10) NOT NULL DEFAULT 'шт.',
  is_service boolean NOT NULL DEFAULT false, vat_rate int NOT NULL DEFAULT 20,
  retail_price numeric(12,2) NOT NULL, purchase_price numeric(12,2) NOT NULL);
CREATE TABLE counterparties (
  id serial PRIMARY KEY, name text NOT NULL, inn varchar(12), kpp varchar(9),
  kind text NOT NULL CHECK (kind IN ('Покупатель','Поставщик')),
  city text, address text, phone text);
CREATE TABLE departments (id serial PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE employees (
  id serial PRIMARY KEY, tab_number varchar(10) UNIQUE, full_name text NOT NULL,
  position text, department_id int REFERENCES departments(id),
  salary numeric(12,2), hire_date date);
CREATE TABLE warehouses (id serial PRIMARY KEY, name text NOT NULL, responsible_id int REFERENCES employees(id));
CREATE TABLE purchase_docs (
  id serial PRIMARY KEY, doc_number varchar(20) UNIQUE NOT NULL, doc_date date NOT NULL,
  supplier_id int REFERENCES counterparties(id), warehouse_id int REFERENCES warehouses(id),
  total numeric(14,2) NOT NULL);
CREATE TABLE purchase_lines (
  id serial PRIMARY KEY, doc_id int REFERENCES purchase_docs(id) ON DELETE CASCADE,
  item_id int REFERENCES nomenclature(id), qty numeric(12,3) NOT NULL, price numeric(12,2) NOT NULL,
  amount numeric(14,2) GENERATED ALWAYS AS (qty*price) STORED);
CREATE TABLE sales_docs (
  id serial PRIMARY KEY, doc_number varchar(20) UNIQUE NOT NULL, doc_date date NOT NULL,
  customer_id int REFERENCES counterparties(id), manager_id int REFERENCES employees(id),
  warehouse_id int REFERENCES warehouses(id), total numeric(14,2) NOT NULL);
CREATE TABLE sales_lines (
  id serial PRIMARY KEY, doc_id int REFERENCES sales_docs(id) ON DELETE CASCADE,
  item_id int REFERENCES nomenclature(id), qty numeric(12,3) NOT NULL, price numeric(12,2) NOT NULL,
  amount numeric(14,2) GENERATED ALWAYS AS (qty*price) STORED);
CREATE TABLE payments (
  id serial PRIMARY KEY, pay_date date NOT NULL, sales_doc_id int REFERENCES sales_docs(id),
  customer_id int REFERENCES counterparties(id), amount numeric(14,2) NOT NULL,
  pay_type text NOT NULL CHECK (pay_type IN ('Безналичный','Наличный')));
CREATE INDEX ON sales_docs(doc_date); CREATE INDEX ON sales_lines(doc_id);
CREATE INDEX ON purchase_lines(doc_id); CREATE INDEX ON payments(sales_doc_id);

